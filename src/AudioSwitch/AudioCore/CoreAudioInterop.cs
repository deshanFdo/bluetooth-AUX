[StructLayout(LayoutKind.Explicit, Size = 24)]
internal struct PropVariant
{
    [FieldOffset(0)] public ushort vt;
    [FieldOffset(2)] public ushort wReserved1;
    [FieldOffset(4)] public ushort wReserved2;
    [FieldOffset(6)] public ushort wReserved3;
    [FieldOffset(8)] public IntPtr ptrVal;
    [FieldOffset(8)] public uint uintVal;
    [FieldOffset(8)] public int intVal;
    [FieldOffset(16)] public IntPtr ptrVal2;

    public string? GetStringValue()
    {
        // VT_LPWSTR = 31
        if (vt == 31 && ptrVal != IntPtr.Zero)
        {
            return Marshal.PtrToStringUni(ptrVal);
        }
        return null;
    }

    public uint? GetUIntValue()
    {
        // VT_UI4 = 19, VT_I4 = 3
        if (vt == 19) return uintVal;
        if (vt == 3) return unchecked((uint)intVal);
        return null;
    }

    [DllImport("ole32.dll")]
    public static extern int PropVariantClear(ref PropVariant pvar);
}

